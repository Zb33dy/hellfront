export type Lang = 'en' | 'tr';

let current: Lang = 'en';
const listeners = new Set<() => void>();

export function setLang(l: Lang): void {
  if (l === current) return;
  current = l;
  listeners.forEach((f) => f());
}
export function getLang(): Lang {
  return current;
}
export function onLangChange(f: () => void): void {
  listeners.add(f);
}

